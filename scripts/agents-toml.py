#!/usr/bin/env python3
"""Write each agents/<name>.toml, Codex's custom agent, from agents/<name>.md.

The Markdown file is the source. Its frontmatter gives `name` and
`description`, and its body after the frontmatter becomes
`developer_instructions`, unchanged. The other frontmatter keys,
`tools` and `model`, are Claude Code's, and mean something else to Codex.

    scripts/agents-toml.py            write every .toml
    scripts/agents-toml.py --check    exit 1, naming each .toml that is
                                      missing or stale

Either way it exits 1 on a .toml with no .md, which it names and leaves
for you to remove.
"""

import json
import sys
import tomllib
from pathlib import Path

AGENTS = Path(__file__).resolve().parent.parent / "agents"
KEYS = ("name", "description")


def frontmatter(text: str, source: str) -> tuple[dict[str, str], str]:
    """Split a Markdown file into its frontmatter keys and its body."""
    if not text.startswith("---\n"):
        sys.exit(f"{source}: no frontmatter")
    end = text.find("\n---\n", 3)
    if end == -1:
        sys.exit(f"{source}: frontmatter not closed")
    keys: dict[str, str] = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            sys.exit(f"{source}: not a key: {line!r}")
        value = value.strip()
        if value.startswith('"'):
            value = json.loads(value)
        elif value.startswith(("'", "[", "{", "|", ">")):
            sys.exit(f"{source}: {key}: only plain or double-quoted values")
        keys[key.strip()] = value
    return keys, text[end + len("\n---\n") :]


def basic(value: str) -> str:
    """A TOML basic string: JSON's escapes are TOML's.

    JSON leaves DEL as it is, and TOML allows it only escaped.
    """
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def multiline(value: str) -> str:
    """A TOML multi-line basic string holding `value` exactly."""
    out: list[str] = []
    quotes = 0
    for i, char in enumerate(value, 1):
        if char == '"':
            # no run of three quotes, and none against the closing ones
            escape = quotes == 2 or i == len(value)
            out.append('\\"' if escape else char)
            quotes = 0 if escape else quotes + 1
            continue
        quotes = 0
        if char == "\\":
            out.append("\\\\")
        elif char in "\n\t":
            out.append(char)
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    # the newline after the opening delimiter is not part of the string
    return f'"""\n{"".join(out)}"""'


def render(md: Path) -> str:
    """The .toml text for one agent's Markdown file."""
    source = f"agents/{md.name}"
    keys, body = frontmatter(md.read_text(encoding="utf-8"), source)
    for key in KEYS:
        if not keys.get(key):
            sys.exit(f"{source}: no {key}")
    text = (
        f"# Generated by scripts/agents-toml.py from {source}: edit that\n"
        "# file and run the script, never this one.\n"
        f"name = {basic(keys['name'])}\n"
        f"description = {basic(keys['description'])}\n"
        f"developer_instructions = {multiline(body)}\n"
    )
    values = {k: keys[k] for k in KEYS} | {"developer_instructions": body}
    try:
        parsed = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        sys.exit(f"{source}: the .toml written is not TOML: {error}")
    if parsed != values:
        sys.exit(f"{source}: the .toml written does not read back as the .md")
    return text


def main() -> None:
    """Write the .toml files, or with --check say which are stale."""
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        sys.exit(__doc__)
    wanted = {md.with_suffix(".toml"): render(md) for md in AGENTS.glob("*.md")}
    stale = [
        toml
        for toml, text in sorted(wanted.items())
        if not toml.exists() or toml.read_text(encoding="utf-8") != text
    ]
    for toml in stale:
        if check:
            print(f"agents/{toml.name} is stale: run scripts/agents-toml.py")
        else:
            toml.write_text(wanted[toml], encoding="utf-8")
            print(f"wrote agents/{toml.name}")
    orphans = sorted(set(AGENTS.glob("*.toml")) - set(wanted))
    for toml in orphans:
        print(f"agents/{toml.name} has no agents/{toml.stem}.md: remove it")
    sys.exit(1 if orphans or (check and stale) else 0)


if __name__ == "__main__":
    main()
